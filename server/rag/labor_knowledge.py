# 建筑劳务法规知识库（RAG核心）
LABOR_REGULATIONS = {
    "建筑工人实名制管理办法": "施工现场必须落实人员实名制，一人一卡，进场必录，退场必销，未落实可处以项目合同造价2%以下罚款。",
    "劳务合同法规": "建立劳动关系必须签订书面劳动合同，约定工资标准、工时、支付周期，禁止拖欠农民工工资。",
    "安全生产规范": "进入施工现场必须佩戴安全帽，高空作业系安全带，特种作业人员必须持证上岗。",
    "工资支付条例": "工资必须按月足额支付，不得低于当地最低工资标准，严禁以实物抵扣工资。",
    "劳务纠纷处理": "发生劳资纠纷应优先调解，调解不成可向住建部门投诉或申请劳动仲裁。",
    "电子合同法律效力": "符合可靠电子签名的电子合同与纸质合同具有同等法律效力，可用于司法举证。"
}

def search_knowledge(query: str) -> str:
    """RAG检索：根据问题匹配法规知识"""
    result = []
    query = query.lower()
    for k, v in LABOR_REGULATIONS.items():
        if any(word in query for word in ["实名制", "合同", "工资", "安全", "纠纷", "合规", "法律", "罚款"]):
            if any(w in k for w in ["实名制", "合同", "安全", "纠纷", "工资"]):
                result.append(f"【{k}】\n{v}")
    return "\n\n".join(result) if result else "未检索到相关劳务法规"